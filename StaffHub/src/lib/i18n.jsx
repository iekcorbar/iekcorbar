const Ctx = createContext(null);

function readLang() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && LANGS.includes(saved)) return saved;
    const nav = String(navigator.language || '').slice(0, 2);
    if (LANGS.includes(nav)) return nav;
  } catch { }
  return 'nl';
}

/** Vertaal een (server-)bericht met de op dat moment gekozen taal.
 *  Werkt ook buiten React (jsend/helpers): leest de taal uit localStorage. */
export function trServer(msg) {
  const k = API_MSG[String(msg || '')];
  let lang = 'nl';
  try { lang = readLang(); } catch { }
  const v = k && DICT[lang] && DICT[lang][k];
  return v || (k && DICT.nl[k]) || msg;
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState('nl');
  useEffect(() => { setLangState(readLang()); }, []);
  useEffect(() => { try { document.documentElement.lang = lang; } catch { } }, [lang]);
  const setLang = useCallback((l) => {
    try { localStorage.setItem(STORE_KEY, l); } catch { }
    setLangState(l);
  }, []);
  const t = useCallback((key, vars) => {
    let v = (DICT[lang] && DICT[lang][key]) || DICT.nl[key] || key;
    if (vars) for (const [k2, val] of Object.entries(vars)) v = v.replace('{' + k2 + '}', val);
    return v;
  }, [lang]);
  const tr = useCallback((msg) => {
    const k = API_MSG[String(msg || '')];
    if (!k) return msg;
    return (DICT[lang] && DICT[lang][k]) || DICT.nl[k] || msg;
  }, [lang]);
  return <Ctx.Provider value={{ lang, setLang, t, tr, locale: lang }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx) || { lang: 'nl', setLang: () => { }, t: (k) => k, tr: (m) => m, locale: 'nl' };
}

/** Datum-formaatteerder in de gekozen taal (Hub + panelen). */
export function useDt() {
  const { locale } = useLang();
  return useCallback((ms) => new Date(ms).toLocaleDateString(locale, {
    day: 'short', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
  }), [locale]);
}

/** Klein NL→EN→IT-wisseler-knopgetje, te gebruiken in header en login. */
export function LangToggle({ className }) {
  const { lang, setLang, t } = useLang();
  return (
    <button title={t('tip.lang')} onClick={() => setLang(LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length])}
      className={className || 'px-1.5 py-1 rounded hover:bg-white/10 text-[10px] font-bold text-parch/70 border border-bronze/30'}>
      {lang.toUpperCase()}
    </button>
  );
}
