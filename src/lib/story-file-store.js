// Where Story Room uploads live on disk. Server-only.
//
// Outside public/ on purpose (same reasoning as api/admin/files): files in
// public/uploads/** are served to anyone through app.js's /uploads/*
// passthrough, but Story Room files must only be readable through
// /api/story/files/raw, which checks Story Room access first. make-zip.js
// doesn't ship private-uploads/, so a deploy never overwrites these files —
// but don't delete that folder on the server either.
import fs from 'fs';
import path from 'path';

export const STORY_FILES_DIR = path.join(process.cwd(), 'private-uploads', 'story-files');

// stored names are generated by us (uuid + safe extension); this guard
// only exists so a corrupted row can never point outside the folder.
export function storyFilePath(storedName) {
  const name = path.basename(String(storedName || ''));
  if (!name || name !== storedName) return null;
  return path.join(STORY_FILES_DIR, name);
}

export async function readStoryFile(storedName) {
  const p = storyFilePath(storedName);
  if (!p) return null;
  try {
    return await fs.promises.readFile(p);
  } catch {
    return null;
  }
}
